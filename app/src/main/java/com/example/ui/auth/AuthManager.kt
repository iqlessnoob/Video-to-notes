package com.example.ui.auth

import android.app.Activity
import android.content.Context
import android.util.Log
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import com.example.R
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential.Companion.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
import com.google.firebase.FirebaseApp
import com.google.firebase.FirebaseOptions
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.launch
import kotlinx.coroutines.tasks.await

data class AuthenticatedSessionUser(
    val uid: String,
    val email: String,
    val displayName: String,
    val isFirebaseBacked: Boolean
)

object AuthManager {
    private const val TAG = "Auth"

    /**
     * Ensures FirebaseApp is initialized so FirebaseAuth.getInstance() does not throw
     * IllegalStateException if google-services.json has not yet been generated by ProvisionFirebase.
     */
    fun ensureFirebaseInitialized(context: Context) {
        try {
            if (FirebaseApp.getApps(context).isEmpty()) {
                FirebaseApp.initializeApp(
                    context.applicationContext,
                    FirebaseOptions.Builder()
                        .setApplicationId(context.packageName)
                        .setProjectId("demo-no-project")
                        .setApiKey("AIzaSyPlaceholderKeyUntilProvisioned")
                        .build()
                )
            }
        } catch (e: Exception) {
            Log.w(TAG, "Firebase initialization check: ${e.message}")
        }
    }

    /**
     * 1. Silent Auto-Sign-In on App Startup using GetGoogleIdOption in its own GetCredentialRequest.
     */
    fun attemptAutoSignIn(
        context: Context,
        credentialManager: CredentialManager,
        onAuthSuccess: (AuthenticatedSessionUser) -> Unit,
        onUnauthenticated: () -> Unit,
        scope: CoroutineScope
    ) {
        ensureFirebaseInitialized(context)
        val existingUser = try {
            FirebaseAuth.getInstance().currentUser
        } catch (_: Exception) {
            null
        }
        if (existingUser != null) {
            onAuthSuccess(
                AuthenticatedSessionUser(
                    uid = existingUser.uid,
                    email = existingUser.email ?: "${existingUser.uid}@student.edu",
                    displayName = existingUser.displayName ?: "Student Scholar",
                    isFirebaseBacked = true
                )
            )
            return
        }

        val clientId = try {
            context.getString(R.string.default_web_client_id)
        } catch (e: Exception) {
            onUnauthenticated()
            return
        }

        if (clientId.isBlank() || clientId == "PENDING_FIREBASE_PROVISIONING_WEB_CLIENT_ID") {
            onUnauthenticated()
            return
        }

        val googleIdOption = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(true)
            .setServerClientId(clientId)
            .setAutoSelectEnabled(true)
            .build()

        val request = GetCredentialRequest.Builder()
            .addCredentialOption(googleIdOption)
            .build()

        scope.launch {
            try {
                val result = credentialManager.getCredential(context, request)
                val credential = result.credential
                if (credential is CustomCredential && credential.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                    val googleIdToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
                    val authCredential = GoogleAuthProvider.getCredential(googleIdToken, null)
                    val authResult = FirebaseAuth.getInstance().signInWithCredential(authCredential).await()
                    val fbUser = authResult.user
                    if (fbUser != null) {
                        onAuthSuccess(
                            AuthenticatedSessionUser(
                                uid = fbUser.uid,
                                email = fbUser.email ?: "${fbUser.uid}@student.edu",
                                displayName = fbUser.displayName ?: "Student Scholar",
                                isFirebaseBacked = true
                            )
                        )
                    } else {
                        onUnauthenticated()
                    }
                } else {
                    onUnauthenticated()
                }
            } catch (e: Exception) {
                onUnauthenticated()
            }
        }
    }

    /**
     * 2. Interactive Google Sign-In using GetSignInWithGoogleOption in its own GetCredentialRequest.
     */
    fun onGoogleSignInClicked(
        context: Context,
        credentialManager: CredentialManager,
        onAuthSuccess: (AuthenticatedSessionUser) -> Unit,
        onAuthError: (String) -> Unit,
        scope: CoroutineScope,
        onAuthCancelled: () -> Unit = {}
    ) {
        ensureFirebaseInitialized(context)
        val clientId = try {
            context.getString(R.string.default_web_client_id)
        } catch (e: Exception) {
            onAuthError("Google Sign-In configuration missing: default_web_client_id not found.")
            return
        }

        val signInOption = GetSignInWithGoogleOption.Builder(serverClientId = clientId).build()
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(signInOption)
            .build()

        scope.launch {
            try {
                val activityContext = context as? Activity ?: context
                val result = credentialManager.getCredential(activityContext, request)
                val credential = result.credential
                if (credential is CustomCredential && credential.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                    val googleIdToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
                    val authCredential = GoogleAuthProvider.getCredential(googleIdToken, null)
                    val authResult = FirebaseAuth.getInstance().signInWithCredential(authCredential).await()
                    val fbUser = authResult.user
                    if (fbUser != null) {
                        onAuthSuccess(
                            AuthenticatedSessionUser(
                                uid = fbUser.uid,
                                email = fbUser.email ?: "${fbUser.uid}@student.edu",
                                displayName = fbUser.displayName ?: "Student Scholar",
                                isFirebaseBacked = true
                            )
                        )
                    } else {
                        onAuthError("Firebase Authentication returned no user record.")
                    }
                } else {
                    onAuthError("Unexpected credential type returned from Credential Manager.")
                }
            } catch (e: GetCredentialCancellationException) {
                Log.w(TAG, "Google Sign-In cancelled or dismissed: ${e.message}", e)
                onAuthCancelled()
            } catch (e: Exception) {
                Log.e(TAG, "Google Sign-In failed", e)
                onAuthError(
                    e.localizedMessage
                        ?: "Google Sign-In could not complete. Ensure Firebase setup is approved in AI Studio."
                )
            }
        }
    }

    /**
     * 3. Sign-Out Flow (Signs out of Firebase AND clears Credential Manager state).
     */
    fun signOut(
        context: Context,
        credentialManager: CredentialManager,
        onSignOutComplete: () -> Unit,
        scope: CoroutineScope
    ) {
        try {
            FirebaseAuth.getInstance().signOut()
        } catch (_: Exception) {
        }
        scope.launch {
            try {
                credentialManager.clearCredentialState(ClearCredentialStateRequest())
            } catch (e: Exception) {
                Log.e(TAG, "Failed to clear credential state", e)
            } finally {
                onSignOutComplete()
            }
        }
    }
}
